local stub = dofile(ADDON_ROOT .. "/tests/wowstub.lua")

local function fresh()
    stub.reset()
    local ns = {}
    harness.load("Display.lua", ns)
    return ns.Display
end

test("Read returns clamped numbers from the CVars", function()
    local Display = fresh()
    local v = Display.Read()
    near(v.gamma, 1.2, "gamma")
    eq(v.brightness, 50, "brightness")
    eq(v.contrast, 50, "contrast")
    stub.cvars.Gamma = "9"
    near(Display.Read().gamma, 2.8, "gamma clamped")
end)

test("Normalize clamps and snaps to the step", function()
    local Display = fresh()
    near(Display.Normalize("gamma", 1.2000000476837), 1.2)
    near(Display.Normalize("gamma", 1.33), 1.35)
    near(Display.Normalize("gamma", 0.1), 0.3)
    near(Display.Normalize("gamma", 5), 2.8)
    eq(Display.Normalize("brightness", 49.6), 50)
    eq(Display.Normalize("contrast", -3), 0)
    eq(Display.Normalize("contrast", 140), 100)
end)

test("Apply without seconds writes at once", function()
    local Display = fresh()
    Display.Apply({ gamma = 1.5, brightness = 60, contrast = 40 })
    near(stub.cvar("Gamma"), 1.5)
    eq(stub.cvar("Brightness"), 60)
    eq(stub.cvar("Contrast"), 40)
    eq(Display.IsFading(), false)
end)

test("Apply with seconds fades linearly and lands exactly on the target", function()
    local Display = fresh()
    stub.cvars.Gamma = "1.0"
    Display.Apply({ gamma = 2.0, brightness = 50, contrast = 50 }, 5)
    eq(Display.IsFading(), true)
    near(stub.cvar("Gamma"), 1.0, "nothing written before the first tick")
    stub.advance(2.5)
    near(stub.cvar("Gamma"), 1.5, "halfway")
    eq(Display.IsFading(), true)
    stub.advance(2.5)
    near(stub.cvar("Gamma"), 2.0, "end")
    eq(Display.IsFading(), false)
end)

test("OnFadeFinished fires once when the fade completes", function()
    local Display = fresh()
    local calls = 0
    Display.OnFadeFinished = function() calls = calls + 1 end
    Display.Apply({ gamma = 2.0, brightness = 50, contrast = 50 }, 5)
    stub.advance(4)
    eq(calls, 0)
    stub.advance(2)
    eq(calls, 1)
end)

test("a new Apply during a fade restarts from the current values", function()
    local Display = fresh()
    stub.cvars.Gamma = "1.0"
    Display.Apply({ gamma = 2.0, brightness = 50, contrast = 50 }, 5)
    stub.advance(2.5)
    Display.Apply({ gamma = 1.0, brightness = 50, contrast = 50 }, 5)
    stub.advance(2.5)
    near(stub.cvar("Gamma"), 1.25, "halfway back from 1.5")
    stub.advance(2.5)
    near(stub.cvar("Gamma"), 1.0)
    eq(Display.IsFading(), false)
end)

test("an instant Apply cancels a running fade", function()
    local Display = fresh()
    Display.Apply({ gamma = 2.0, brightness = 50, contrast = 50 }, 5)
    stub.advance(1)
    Display.Apply({ gamma = 1.1, brightness = 50, contrast = 50 }, 0)
    eq(Display.IsFading(), false)
    stub.advance(10)
    near(stub.cvar("Gamma"), 1.1)
end)

test("no fade is started when the target equals the current values", function()
    local Display = fresh()
    Display.Apply({ gamma = 1.2, brightness = 50, contrast = 50 }, 5)
    eq(Display.IsFading(), false)
end)

test("a missing Contrast CVar is skipped everywhere", function()
    local Display = fresh()
    stub.cvars.Contrast = nil
    eq(Display.HasContrast(), false)
    eq(Display.Read().contrast, nil)
    Display.Apply({ gamma = 1.5, brightness = 60, contrast = 40 })
    eq(stub.cvars.Contrast, nil)
    near(stub.cvar("Gamma"), 1.5)
    Display.Apply({ gamma = 2.0, brightness = 60, contrast = 10 }, 5)
    stub.advance(6)
    eq(stub.cvars.Contrast, nil)
    near(stub.cvar("Gamma"), 2.0)
end)
